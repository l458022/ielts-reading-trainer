  var MAP = null;
  function parse() {
    if (MAP) return MAP;
    MAP = {};
    RAW.trim().split("\n").forEach(function (line) {
      var parts = line.split("|");
      if (parts.length >= 3 && parts[0].trim()) {
        MAP[parts[0].trim().toLowerCase()] = { pos: parts[1].trim(), meaning: parts.slice(2).join("|").trim() };
      }
    });
    return MAP;
  }
  // 词形还原候选：colonies→colony, increased→increase, studying→study...
  function stemCandidates(w) {
    var c = [w];
    if (/ies$/.test(w)) c.push(w.replace(/ies$/, "y"));
    if (/(ches|shes|sses|xes)$/.test(w)) c.push(w.slice(0, -2));
    if (/s$/.test(w) && !/ss$/.test(w)) c.push(w.slice(0, -1));
    if (/ied$/.test(w)) c.push(w.replace(/ied$/, "y"));
    if (/ed$/.test(w)) { c.push(w.slice(0, -1)); c.push(w.slice(0, -2)); }
    if (/ing$/.test(w)) { c.push(w.slice(0, -3)); c.push(w.slice(0, -3) + "e"); }
    if (/ly$/.test(w)) c.push(w.slice(0, -2));
    if (/(er|est)$/.test(w)) c.push(w.slice(0, -2));
    return c;
  }
  // 查询：返回 { word, pos, meaning, note } 或 null
  function lookup(word) {
    var map = parse();
    var w = String(word || "").toLowerCase().replace(/[^a-z-]/g, "");
    if (!w || w.length < 2) return null;
    var cands = stemCandidates(w);
    for (var i = 0; i < cands.length; i++) {
      if (map[cands[i]]) {
        var hit = map[cands[i]];
        return {
          word: cands[i], pos: hit.pos, meaning: hit.meaning,
          note: cands[i] !== w ? ("词形还原：" + w + " → " + cands[i]) : null
        };
      }
    }
    return null;
  }
  return { lookup: lookup, parse: parse, RAW: RAW };
